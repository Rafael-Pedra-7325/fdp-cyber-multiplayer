def get_deck_stats():
    """Retorna contagem detalhada por pacote e totais."""
    stats = {}
    total_white = 0
    total_black = 0
    for key, meta in DECK_METADATA.items():
        w = len(WHITE_DECKS.get(key, []))
        b = len(BLACK_DECKS.get(key, []))
        total_white += w
        total_black += b
        stats[key] = {
            **meta,
            "white_count": w,
            "black_count": b,
            "total": w + b,
        }
    return {
        "decks": stats,
        "total_white": total_white,
        "total_black": total_black,
        "grand_total": total_white + total_black,
    }
